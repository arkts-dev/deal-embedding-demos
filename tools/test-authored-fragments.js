"use strict";
// Production compiler/session and authored fragment modules; no inference.
const fs=require('fs'),vm=require('vm'),assert=require('assert');
let harness=fs.readFileSync('tools/test-behavior-session.js','utf8');
harness=harness.slice(0,harness.indexOf('(async()=>'));
globalThis.require=require;vm.runInThisContext(harness);
let s=mount('composed-budget');
assert.equal(state(s).m_balanceDifference,1750);
const root=snapshot(s).tree;
const screen=nodes(root).find(n=>n.component.endsWith('.Screen'));
assert(screen,'Maintained composition must use a screen recipe');
assert.deepEqual(screen.children.map(n=>n.component.split('.').pop()),['Hero','MetricGroup','Section']);
assert.equal(nodes(screen).filter(n=>n.component.endsWith('.Hero')).length,1,'One task heading');
assert.equal(nodes(screen).filter(n=>n.component.endsWith('.InputGroup')).length,1,'Related editable controls grouped');
s.dispatch(slot(s,'Approved'),'20000');
assert.equal(state(s).m_balanceDifference,-250);
s.dispose();
let provider=mount('composed-departure');
const providerScreen=nodes(snapshot(provider).tree).find(n=>n.component.endsWith('.Screen'));
const commandGroup=nodes(providerScreen).find(n=>n.component.endsWith('.Section')&&nodes(n).some(c=>c.component.endsWith('.PrimaryAction')));
assert(commandGroup,'Provider command must be inside its contextual section');
assert(nodes(commandGroup).some(n=>n.component.endsWith('.InputGroup')),'Command shares section with dependent inputs');
assert(!providerScreen.children.some(n=>n.component.endsWith('.PrimaryAction')),'No trailing command dump');
provider.dispose();
s=mount('composed-budget');
s.dispatch(slot(s,'Approved'),'20000');
assert.equal(state(s).m_balanceDifference,-250);
assert.equal(state(s).m_balanceMagnitude,250);
assert.equal(state(s).m_balanceStatus,'Under budget');
s.dispatch(slot(s,'Approved'),'1.5');
assert.equal(state(s).m_approvedValue,20000);
s.dispatch(slot(s,'Approved'),'-1');
assert.equal(state(s).m_approvedValue,20000);
s.dispatch(slot(s,'Committed'),'20000');
assert.equal(state(s).m_balanceStatus,'Equal');
const saved=JSON.parse(s.checkpoint());s.dispose();
s=mount('composed-budget',saved);
assert.equal(state(s).m_balanceDifference,0);s.dispose();
s=mount('composed-inputs');
s.dispatch(slot(s,'First text'),'changed');
assert.equal(state(s).m_firstValue,'changed');
assert.equal(state(s).m_secondValue,'same');
s.dispatch(slot(s,'Enabled'),'');
assert.equal(state(s).m_enabledValue,false);
s.dispatch(slot(s,'Start minute'),'1.5');assert.equal(state(s).m_startValue,600);
s.dispatch(slot(s,'Start minute'),'1440');assert.equal(state(s).m_startValue,600);
s.dispatch(slot(s,'Start minute'),'1439');assert.equal(state(s).m_startValue,1439);
s.dispose();
console.log('PASS authored input/comparison: initialization, updates, bounds, signed comparison, equality and settled restoration.');
